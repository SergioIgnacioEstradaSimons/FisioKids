-- ---------- TABLAS ----------
create table if not exists public.usuarios (
  id            integer generated by default as identity primary key,
  auth_id       uuid unique references auth.users(id) on delete set null,  -- vínculo con el login de Supabase
  nombres       text not null,
  apellidos     text not null,
  correo        text not null,
  rol           text not null check (rol in ('admin','profesional')),
  especialidad  text,
  activo        integer not null default 1,
  foto          text                                                         -- foto de perfil (base64), opcional
);
create unique index if not exists usuarios_correo_uq on public.usuarios (lower(correo));
create unique index if not exists usuarios_nombre_uq on public.usuarios (lower(nombres), lower(apellidos));

create table if not exists public.ninos (
  id                integer generated by default as identity primary key,
  nombres           text not null,
  apellidos         text not null,
  fecha_nacimiento  text not null,
  tipo_discapacidad text not null,
  grado             text not null check (grado in ('Leve','Moderado','Grave','Muy grave')),
  tutor_nombre      text not null,
  tutor_telefono    text not null,
  observaciones     text,
  activo            integer not null default 1
);
create unique index if not exists ninos_uq on public.ninos (lower(nombres), lower(apellidos), fecha_nacimiento);

create table if not exists public.salas (
  id        integer generated by default as identity primary key,
  nombre    text not null unique,
  capacidad integer not null default 4,
  activo    integer not null default 1
);

create table if not exists public.bloques (
  id             integer generated by default as identity primary key,
  dia_semana     integer not null,           -- 1 = lunes ... 5 = viernes
  hora_inicio    text not null,
  hora_fin       text not null,
  actividad      text not null,
  profesional_id integer not null references public.usuarios(id),
  sala_id        integer not null references public.salas(id)
);

create table if not exists public.asignaciones (
  id        integer generated by default as identity primary key,
  bloque_id integer not null references public.bloques(id) on delete cascade,
  nino_id   integer not null references public.ninos(id)   on delete cascade,
  unique (bloque_id, nino_id)
);

create table if not exists public.asistencias (
  id            integer generated by default as identity primary key,
  bloque_id     integer not null references public.bloques(id) on delete cascade,
  nino_id       integer not null references public.ninos(id)   on delete cascade,
  fecha         text not null,
  estado        text not null check (estado in ('Presente','Falta')),
  actividades   text,
  observaciones text,
  unique (bloque_id, nino_id, fecha)
);

create table if not exists public.cierres_bloque (
  id          integer generated by default as identity primary key,
  bloque_id   integer not null references public.bloques(id) on delete cascade,
  fecha       text not null,
  cerrado_por integer references public.usuarios(id),
  unique (bloque_id, fecha)
);

create table if not exists public.tipos_discapacidad (
  id     integer generated by default as identity primary key,
  nombre text not null,
  activo integer not null default 1
);
create unique index if not exists tipos_nombre_uq on public.tipos_discapacidad (lower(nombre));

create table if not exists public.avisos_leidos (
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  clave      text not null,
  primary key (usuario_id, clave)
);

create table if not exists public.suspensiones (
  id     integer generated by default as identity primary key,
  fecha  text not null unique,
  motivo text not null,
  origen text not null default 'manual'      -- 'api' o 'manual'
);

-- Índices para las consultas más usadas
create index if not exists idx_bloques_prof_dia   on public.bloques (profesional_id, dia_semana);
create index if not exists idx_asist_fecha        on public.asistencias (fecha);
create index if not exists idx_asist_nino         on public.asistencias (nino_id);

-- ---------- FUNCIONES AUXILIARES DE SEGURIDAD ----------
-- Quién soy yo (según el login) y si soy administrador. SECURITY DEFINER evita bucles con RLS.
create or replace function public.mi_id() returns integer
language sql stable security definer set search_path = public as $$
  select id from public.usuarios where auth_id = auth.uid() and activo = 1 limit 1;
$$;

create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.usuarios where auth_id = auth.uid() and rol = 'admin' and activo = 1);
$$;

create or replace function public.es_mi_bloque(p_bloque integer) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.bloques where id = p_bloque and profesional_id = public.mi_id());
$$;

-- ---------- VÍNCULO LOGIN <-> USUARIOS ----------
-- Cuando se crea un usuario en Authentication, se enlaza solo con la fila de `usuarios` que tenga el mismo correo.
create or replace function public.enlazar_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.usuarios set auth_id = new.id
   where lower(correo) = lower(new.email) and auth_id is null;
  return new;
end $$;

drop trigger if exists al_crear_auth_user on auth.users;
create trigger al_crear_auth_user after insert on auth.users
  for each row execute function public.enlazar_usuario();

-- Un profesional puede editar su perfil (nombres, apellidos, foto) pero NO su rol, estado, correo ni vínculo.
create or replace function public.proteger_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or public.es_admin() then return new; end if;  -- SQL Editor / admin: sin restricción
  new.rol := old.rol; new.activo := old.activo; new.correo := old.correo; new.auth_id := old.auth_id;
  return new;
end $$;

drop trigger if exists proteger_usuario_tr on public.usuarios;
create trigger proteger_usuario_tr before update on public.usuarios
  for each row execute function public.proteger_usuario();

-- ---------- SEGURIDAD A NIVEL DE FILA (RLS) ----------
alter table public.usuarios           enable row level security;
alter table public.ninos              enable row level security;
alter table public.salas              enable row level security;
alter table public.bloques            enable row level security;
alter table public.asignaciones       enable row level security;
alter table public.asistencias        enable row level security;
alter table public.cierres_bloque     enable row level security;
alter table public.tipos_discapacidad enable row level security;
alter table public.avisos_leidos      enable row level security;
alter table public.suspensiones       enable row level security;

-- Tablas que todos los usuarios con sesión pueden LEER y solo el admin puede MODIFICAR
do $$
declare t text;
begin
  foreach t in array array['ninos','salas','bloques','asignaciones','tipos_discapacidad','suspensiones'] loop
    execute format('drop policy if exists "leer_%1$s" on public.%1$I', t);
    execute format('drop policy if exists "admin_%1$s" on public.%1$I', t);
    execute format('create policy "leer_%1$s" on public.%1$I for select to authenticated using (true)', t);
    execute format('create policy "admin_%1$s" on public.%1$I for all to authenticated using (public.es_admin()) with check (public.es_admin())', t);
  end loop;
end $$;

-- usuarios: todos leen; el admin crea/borra/edita; cada quien edita SU fila (el trigger limita las columnas)
drop policy if exists leer_usuarios on public.usuarios;
drop policy if exists admin_usuarios on public.usuarios;
drop policy if exists editar_mi_usuario on public.usuarios;
create policy leer_usuarios on public.usuarios for select to authenticated using (true);
create policy admin_usuarios on public.usuarios for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy editar_mi_usuario on public.usuarios for update to authenticated
  using (auth_id = auth.uid()) with check (auth_id = auth.uid());

-- asistencias: todos leen; el admin o el profesional dueño del bloque escriben; solo el admin borra
drop policy if exists leer_asistencias on public.asistencias;
drop policy if exists escribir_asistencias on public.asistencias;
drop policy if exists editar_asistencias on public.asistencias;
drop policy if exists borrar_asistencias on public.asistencias;
create policy leer_asistencias on public.asistencias for select to authenticated using (true);
create policy escribir_asistencias on public.asistencias for insert to authenticated
  with check (public.es_admin() or public.es_mi_bloque(bloque_id));
create policy editar_asistencias on public.asistencias for update to authenticated
  using (public.es_admin() or public.es_mi_bloque(bloque_id)) with check (public.es_admin() or public.es_mi_bloque(bloque_id));
create policy borrar_asistencias on public.asistencias for delete to authenticated using (public.es_admin());

-- cierres_bloque: cerrar = admin o dueño del bloque; reabrir (delete) = solo admin
drop policy if exists leer_cierres on public.cierres_bloque;
drop policy if exists crear_cierres on public.cierres_bloque;
drop policy if exists borrar_cierres on public.cierres_bloque;
create policy leer_cierres on public.cierres_bloque for select to authenticated using (true);
create policy crear_cierres on public.cierres_bloque for insert to authenticated
  with check (public.es_admin() or public.es_mi_bloque(bloque_id));
create policy borrar_cierres on public.cierres_bloque for delete to authenticated using (public.es_admin());

-- avisos_leidos: cada usuario ve y modifica solo los suyos
drop policy if exists mis_avisos on public.avisos_leidos;
create policy mis_avisos on public.avisos_leidos for all to authenticated
  using (usuario_id = public.mi_id()) with check (usuario_id = public.mi_id());

-- Sin sesión (rol anon) no se puede leer ni escribir nada: no hay políticas para `anon`.
