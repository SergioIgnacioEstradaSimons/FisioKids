create table if not exists public.eventos (
  id integer generated by default as identity primary key,
  tipo text not null check (tipo in ('perfil', 'password', 'asignacion')),
  titulo text not null,
  texto text not null,
  grupo text not null default 'Hoy',
  icono text not null default 'bell',
  tono text not null default 'azul',
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  actor_id integer references public.usuarios(id) on delete set null,
  bloque_id integer references public.bloques(id) on delete set null,
  creado_en timestamptz not null default now()
);

create index if not exists idx_eventos_usuario_creado on public.eventos (usuario_id, creado_en desc);
create index if not exists idx_eventos_actor on public.eventos (actor_id);

alter table public.eventos enable row level security;

drop policy if exists "ver_eventos" on public.eventos;
create policy "ver_eventos" on public.eventos
  for select to authenticated
  using (usuario_id = public.mi_id() or public.es_admin());

drop policy if exists "crear_eventos" on public.eventos;
create policy "crear_eventos" on public.eventos
  for insert to authenticated
  with check (
    actor_id = public.mi_id()
    and (
      (
        tipo in ('perfil', 'password')
        and exists (select 1 from public.usuarios a where a.id = actor_id and a.rol = 'profesional')
        and exists (select 1 from public.usuarios d where d.id = usuario_id and d.rol = 'admin')
      )
      or (tipo = 'asignacion' and public.es_admin())
    )
  );

grant select, insert on public.eventos to authenticated;
grant usage on sequence public.eventos_id_seq to authenticated;
